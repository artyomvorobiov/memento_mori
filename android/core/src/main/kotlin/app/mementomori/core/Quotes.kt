    /** Цитата дня: меняется в полночь, одинакова в приложении, виджете и напоминании. */
    fun ofTheDay(date: Instant = Instant.now(), offset: Int = 0, zone: ZoneId = ZoneId.systemDefault()): Quote {
        val index = positiveModulo(dayNumber(date, zone) + offset, all.size)
        return all[index]
    }
